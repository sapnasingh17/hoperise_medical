<?php
/**
 * Hope Rise Medical - SMTP & Email System Diagnostic Verification Tool
 * Accessible via CLI (php test_email.php) or Web Browser (http://localhost/test_email.php)
 */

header('Content-Type: text/plain; charset=utf-8');

echo "=====================================================\n";
echo "  Hope Rise Medical - SMTP Email Diagnostic Tool    \n";
echo "=====================================================\n\n";

// 1. PHP Extensions Check
echo "[1] Checking PHP Extension Requirements:\n";
$extensions = ['openssl', 'sockets', 'mbstring', 'mysqli'];
foreach ($extensions as $ext) {
    $loaded = extension_loaded($ext);
    echo "  - Extension '$ext': " . ($loaded ? "OK (Loaded)" : "WARNING (Not Loaded)") . "\n";
}
echo "\n";

// 2. Load Configuration & PHPMailer
echo "[2] Loading SMTP Configuration & Libraries:\n";
require_once __DIR__ . '/smtp_config.php';
require_once __DIR__ . '/smtp_helper.php';

$host = defined('SMTP_HOST') ? SMTP_HOST : 'smtp.gmail.com';
$port = defined('SMTP_PORT') ? SMTP_PORT : 587;
$user = defined('SMTP_USER') ? SMTP_USER : '';
$pass = defined('SMTP_PASS') ? SMTP_PASS : '';
$secure = defined('SMTP_SECURE') ? SMTP_SECURE : 'tls';
$from = defined('SMTP_FROM_EMAIL') ? SMTP_FROM_EMAIL : '';
$name = defined('SMTP_FROM_NAME') ? SMTP_FROM_NAME : '';

$pass_masked = !empty($pass) ? (substr($pass, 0, 3) . '****' . substr($pass, -3)) : '[EMPTY / UNSET]';

echo "  - SMTP Host      : $host\n";
echo "  - SMTP Port      : $port\n";
echo "  - SMTP Username  : $user\n";
echo "  - SMTP Password  : $pass_masked\n";
echo "  - Encryption     : $secure\n";
echo "  - From Email     : $from\n";
echo "  - From Name      : $name\n";
echo "\n";

// 3. Socket Connectivity Test
echo "[3] Testing Socket Connection to {$host}:{$port}...\n";
$socket_timeout = 5;
$fp = @fsockopen($host, $port, $errno, $errstr, $socket_timeout);
if ($fp) {
    echo "  - Socket Connection SUCCESSFUL to {$host}:{$port}\n";
    fclose($fp);
} else {
    echo "  - Socket Connection FAILED: Error {$errno} - {$errstr}\n";
    echo "  - Troubleshooting Note: Check firewall, port availability, or outbound connectivity.\n";
}
echo "\n";

// 4. Send Test Email Attempt
$recipient = isset($_GET['to']) ? trim($_GET['to']) : (getenv('TEST_EMAIL_TO') ?: $from);
if (empty($recipient) || !filter_var($recipient, FILTER_VALIDATE_EMAIL)) {
    $recipient = 'sapnnna988@gmail.com';
}

echo "[4] Dispatching Test Email to: {$recipient}\n";
$subject = "SMTP Test Verification - Hope Rise Medical [" . date('H:i:s') . "]";
$body = "
<h2>SMTP Diagnostic Email Test</h2>
<p>This test email was generated by <strong>test_email.php</strong> to confirm that PHPMailer SMTP email delivery is correctly configured and working.</p>
<ul>
    <li><strong>Timestamp:</strong> " . date('Y-m-d H:i:s T') . "</li>
    <li><strong>Host:</strong> {$host}:{$port}</li>
    <li><strong>Sender:</strong> {$from}</li>
</ul>
<p>If you received this message in your inbox, your SMTP configuration is fully working!</p>
";

$error = '';
$start_time = microtime(true);
$result = send_smtp_email($recipient, $subject, $body, $from, $name, $error);
$duration = round(microtime(true) - $start_time, 3);

echo "\n-----------------------------------------------------\n";
if ($result) {
    echo "RESULT: ✅ SUCCESS! Email delivered in {$duration}s.\n";
    echo "Message successfully accepted by SMTP server for {$recipient}.\n";
} else {
    echo "RESULT: ❌ FAILED! Email delivery failed in {$duration}s.\n";
    echo "Error Details: " . ($error ?: 'Unknown SMTP failure') . "\n";
    echo "Log Check: Please inspect " . (defined('SMTP_DEBUG_LOG') ? SMTP_DEBUG_LOG : 'smtp_errors.log') . " for full stack trace.\n";
}
echo "-----------------------------------------------------\n\n";
